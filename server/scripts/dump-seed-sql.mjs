// ─────────────────────────────────────────────────────────────────────
// Generate a SQL file (server/seed-d1.sql) containing the full demo
// seed — schema + data — for Cloudflare D1.
//
// Runs the real seed logic against an in-memory SQLite so the ledger
// hashes are computed by the same code, then dumps every table to
// INSERT statements.
//
//   Usage:  node server/scripts/dump-seed-sql.mjs
//           npx wrangler d1 execute zemen-db --remote --file=server/seed-d1.sql
// ─────────────────────────────────────────────────────────────────────
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Env must be set before the db layer evaluates — use dynamic imports.
process.env.DB_FILE = ':memory:';
process.env.DATABASE_URL = '';

const { initDb, db } = await import('../src/db.js');
const { initSchema, schemaDdl } = await import('../src/schema.js');
const { runSeed } = await import('../src/seed.js');

const serverRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

async function main() {
  await initDb();
  await initSchema();
  await runSeed();

  const { tables, indexes } = schemaDdl();
  const lines = [
    '-- Zemen demo seed (schema + data) for Cloudflare D1.',
    '-- Generated by server/scripts/dump-seed-sql.mjs.',
    '',
    ...tables.map((t) => t + ';'),
    ...indexes.map((t) => t + ';'),
    '',
  ];

  const TABLES = [
    'users', 'otp_codes', 'transactions', 'ledger',
    'disputes', 'dispute_statements', 'dispute_evidence',
    'dispute_votes', 'dispute_moderator_log', 'dispute_staff_overrides', 'role_audit', 'reputation_scores',
  ];
  const orderBy = { reputation_scores: 'user_id ASC' }; // no `id` column
  for (const t of TABLES) {
    const rows = await db.all(`SELECT * FROM ${t} ORDER BY ${orderBy[t] || 'id ASC'}`);
    for (const r of rows) {
      const cols = Object.keys(r);
      const vals = cols.map((c) => literal(r[c])).join(', ');
      lines.push(`INSERT INTO ${t} (${cols.join(', ')}) VALUES (${vals});`);
    }
    lines.push('');
  }

  const out = path.join(serverRoot, 'seed-d1.sql');
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`  ✔ Wrote ${out} (${fs.statSync(out).size} bytes).`);
  console.log('  Apply it to Cloudflare D1 with:');
  console.log('    npx wrangler d1 execute zemen-db --remote --file=server/seed-d1.sql');
}

main().catch((err) => {
  console.error('Dump failed:', err);
  process.exit(1);
});
